// scripts/gate-spoolman.js - live gate for Spoolman write-back (v2.41)
//
//   node scripts/gate-spoolman.js [http://127.0.0.1:7912]
//
// The harness proves the Hub's side against a mock Spoolman. This proves the
// part a mock cannot: that a REAL Spoolman accepts the Hub's PUT /use calls
// and that its own remaining_weight moves by exactly the grams the Hub
// deducted - and moves back on Undo (negative use).
//
// Point it at a THROWAWAY Spoolman. It creates its own vendor, two filaments
// and two spools there (named "Hub gate ..."), and deletes them at the end.
// The Hub side runs from this clone on port 4548 with an isolated U1HUB_DIR in
// %TEMP% and one MOCK printer - production on 4545 and the real farm are never
// touched. A real printer is not needed: what a print finishing looks like to
// the Hub is already covered; the thing under test here is Spoolman.
"use strict";
const fs = require("fs"), os = require("os"), path = require("path");
const { spawn } = require("child_process");
const { createMock } = require("../test/mock-moonraker.js");

const SM = (process.argv[2] || "http://127.0.0.1:7912").replace(/\/+$/, "");
const REPO = path.join(__dirname, "..");
const PORT = 4548, HUB = "http://127.0.0.1:" + PORT;
const sleep = ms => new Promise(r => setTimeout(r, ms));
let pass = 0, fail = 0;
const ok = (c, name, detail) => { c ? pass++ : fail++; console.log((c ? "  PASS " : "  FAIL ") + name + (c || detail === undefined ? "" : "  -> " + JSON.stringify(detail).slice(0, 300))); };

async function call(base, method, p, body) {
  const r = await fetch(base + p, { method, headers: body ? { "content-type": "application/json" } : {}, body: body ? JSON.stringify(body) : undefined });
  const t = await r.text();
  let j = null; try { j = JSON.parse(t); } catch {}
  if (!r.ok) throw new Error(method + " " + base + p + " -> " + r.status + " " + t.slice(0, 200));
  return j;
}
const sm = (m, p, b) => call(SM, m, "/api/v1" + p, b);
const hub = (m, p, b) => call(HUB, m, p, b);
const GCODE = [
  "; generated by OrcaSlicer", "G28", "T0", "G1 X1", "T1", "G1 X2",
  "; filament_colour = #FF0000;#0000FF", "; filament_type = PLA;PLA",
  "; filament used [g] = 10.0;12.5", "; estimated printing time (normal mode) = 1h 2m"
].join("\n");

(async () => {
  const info = await sm("GET", "/info");
  console.log("Spoolman " + info.version + " at " + SM + " (data: " + info.data_dir + ")");
  const created = { spools: [], filaments: [], vendor: null };
  let child = null, mock = null;
  try {
    // ---- 1. seed the real Spoolman ------------------------------------------
    const v = await sm("POST", "/vendor", { name: "Hub gate vendor" });
    created.vendor = v.id;
    const fil = async (name, hex) => (await sm("POST", "/filament", {
      name, vendor_id: v.id, material: "PLA", density: 1.24, diameter: 1.75, weight: 1000,
      spool_weight: 200, color_hex: hex, settings_extruder_temp: 215, settings_bed_temp: 60 })).id;
    const fRed = await fil("Hub gate Red", "FF0000"), fBlue = await fil("Hub gate Blue", "0000FF");
    created.filaments.push(fRed, fBlue);
    const sRed = (await sm("POST", "/spool", { filament_id: fRed, initial_weight: 1000, remaining_weight: 700 })).id;
    const sBlue = (await sm("POST", "/spool", { filament_id: fBlue, initial_weight: 1000, remaining_weight: 400 })).id;
    created.spools.push(sRed, sBlue);
    const rem = async id => (await sm("GET", "/spool/" + id)).remaining_weight;
    ok(await rem(sRed) === 700 && await rem(sBlue) === 400, "seeded two spools in the real Spoolman (700 g, 400 g)");
    // Spoolman derives used_weight from the seed (1000 initial - 700 left =
    // 300); every later check compares against what it actually reported.
    const used0 = (await sm("GET", "/spool/" + sRed)).used_weight;

    // ---- 2. an isolated Hub with one mock printer ---------------------------
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "u1hub-gate-sm-"));
    const gdir = path.join(dir, "gcode"); fs.mkdirSync(gdir);
    fs.writeFileSync(path.join(gdir, "gate.gcode"), GCODE);
    mock = createMock("u1");
    const mport = await mock.listen(0);
    fs.writeFileSync(path.join(dir, "config.json"), JSON.stringify({
      gcodeFolder: gdir, printers: [{ name: "Gate-U1", url: "http://127.0.0.1:" + mport }],
      features: { spools: true, resources: true, spoolman: true }
    }, null, 2));
    child = spawn(process.execPath, ["server.js"], { cwd: REPO, stdio: ["ignore", "pipe", "pipe"],
      env: { ...process.env, U1HUB_DIR: dir, U1HUB_PORT: String(PORT), U1HUB_EVENTS_POLL_MS: "1000", U1HUB_POLL_MS: "400" } });
    let log = ""; child.stdout.on("data", d => log += d); child.stderr.on("data", d => log += d);
    for (let i = 0; i < 80; i++) { await sleep(250); try { if ((await fetch(HUB + "/api/version")).ok) break; } catch {} }
    ok(!!(await hub("GET", "/api/version")).version, "throwaway Hub up on " + PORT + " (state in " + dir + ")");

    // ---- 3. import, load, switch write-back on ------------------------------
    await hub("POST", "/api/spoolman/settings", { url: SM });
    const imp = await hub("POST", "/api/spoolman/import", {});
    const hRed = "spoolman_" + sRed, hBlue = "spoolman_" + sBlue;
    ok(imp.ok && imp.imported >= 2, "Hub imported from the real Spoolman", imp);
    await hub("GET", "/api/files?type=u1");
    const fleet = await hub("GET", "/api/fleet");
    const pid = (fleet.find(p => p.name === "Gate-U1") || fleet[0]).id;
    await hub("POST", "/api/slots/assign", { printer: pid, slot: 0, spool_id: hRed });
    await hub("POST", "/api/slots/assign", { printer: pid, slot: 1, spool_id: hBlue });
    const wb = await hub("POST", "/api/spoolman/settings", { writeback: true });
    ok(wb.writeback === true, "write-back on");

    // ---- 4. a print finishes ------------------------------------------------
    mock.state.printState = "standby"; await sleep(5000);
    mock.state.printState = "printing"; mock.state.filename = "gate.gcode"; await sleep(5000);
    mock.state.printState = "complete"; mock.state.printDuration = 3600;
    let d = null;
    for (let i = 0; i < 40; i++) {
      await sleep(500);
      d = ((await hub("GET", "/api/resources/deductions")).deductions || [])[0];
      if (d && d.entries.length && d.entries.every(e => e.spoolman && e.spoolman.state !== "pending")) break;
    }
    ok(d && d.file === "gate.gcode" && d.entries.length === 2, "the Hub deducted the finished print", d);
    ok(d && d.entries.every(e => e.spoolman && e.spoolman.state === "sent"), "both uses reached Spoolman", d && d.entries.map(e => e.spoolman));
    const a1 = await rem(sRed), b1 = await rem(sBlue);
    ok(a1 === 690 && b1 === 387.5, "REAL Spoolman: remaining 700 -> 690 and 400 -> 387.5", { red: a1, blue: b1 });
    const used1 = (await sm("GET", "/spool/" + sRed)).used_weight;
    ok(used1 === used0 + 10, "REAL Spoolman: used_weight went up by exactly 10 g", { used0, used1 });

    // ---- 5. Undo -------------------------------------------------------------
    await hub("POST", "/api/resources/deductions/undo", { at: d.at });
    for (let i = 0; i < 20; i++) {
      await sleep(500);
      d = ((await hub("GET", "/api/resources/deductions")).deductions || [])[0];
      if (d.entries.every(e => e.spoolman.state !== "sent")) break;
    }
    ok(d.entries.every(e => e.spoolman.state === "reverted"), "Undo: both uses reverted", d.entries.map(e => e.spoolman));
    const a2 = await rem(sRed), b2 = await rem(sBlue);
    ok(a2 === 700 && b2 === 400, "REAL Spoolman accepts a negative use: back to 700 and 400", { red: a2, blue: b2 });
    const sp = await sm("GET", "/spool/" + sRed);
    ok(sp.used_weight === used0 && sp.filament.name === "Hub gate Red" && sp.filament.color_hex.toUpperCase() === "FF0000",
      "nothing else about the spool changed (used back to " + used0 + " g, name and color intact)", { used: sp.used_weight, used0, name: sp.filament.name, hex: sp.filament.color_hex });
    const st = await hub("GET", "/api/spoolman");
    ok(st.writeback_pending === 0, "nothing left pending", st);
  } catch (e) {
    fail++; console.log("  FAIL gate aborted: " + (e && e.stack || e));
  } finally {
    if (child) { child.kill(); await sleep(500); }
    if (mock && mock.close) await Promise.race([mock.close(), sleep(1000)]);
    for (const id of created.spools) await sm("DELETE", "/spool/" + id).catch(() => {});
    for (const id of created.filaments) await sm("DELETE", "/filament/" + id).catch(() => {});
    if (created.vendor) await sm("DELETE", "/vendor/" + created.vendor).catch(() => {});
    console.log("\n" + pass + " passed, " + fail + " failed" + (fail ? "" : " - Spoolman write-back gate GREEN"));
    process.exit(fail ? 1 : 0);
  }
})();
