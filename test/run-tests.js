// Minimal STORED-method zip builder — enough to fabricate a 3MF fixture for
// the analyze endpoint (a 3MF is just a zip with config members).
function crc32(buf) {
  let t = crc32.T;
  if (!t) {
    t = crc32.T = new Int32Array(256);
    for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c; }
  }
  let c = ~0;
  for (let i = 0; i < buf.length; i++) c = t[(c ^ buf[i]) & 0xFF] ^ (c >>> 8);
  return ~c >>> 0;
}
function buildZip(files) { // [{name, data:Buffer}]
  const locals = [], centrals = [];
  let off = 0;
  for (const f of files) {
    const name = Buffer.from(f.name), data = f.data, crc = crc32(data);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0, 6); lh.writeUInt16LE(0, 8);
    lh.writeUInt32LE(0, 10); lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(data.length, 18); lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(name.length, 26); lh.writeUInt16LE(0, 28);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0, 8); ch.writeUInt16LE(0, 10);
    ch.writeUInt32LE(0, 12); ch.writeUInt32LE(crc, 16); ch.writeUInt32LE(data.length, 20); ch.writeUInt32LE(data.length, 24);
    ch.writeUInt16LE(name.length, 28); ch.writeUInt32LE(off, 42);
    locals.push(lh, name, data);
    centrals.push(Buffer.concat([ch, name]));
    off += 30 + name.length + data.length;
  }
  const cd = Buffer.concat(centrals);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(files.length, 8); eocd.writeUInt16LE(files.length, 10);
  eocd.writeUInt32LE(cd.length, 12); eocd.writeUInt32LE(off, 16);
  return Buffer.concat([...locals, cd, eocd]);
}

// Stage the hub with EXACTLY the Dockerfile's COPY set (Workstream B check).
const DOCKER_SET = ["server.js", "parser.js", "auth.js", "fs-colors.js", "tunnel.js", "rfid.js", "filament-swatches.json", "package.json"];
function stageHub(dir) {
  fs.mkdirSync(dir, { recursive: true });
  for (const f of DOCKER_SET) fs.copyFileSync(path.join(REPO, f), path.join(dir, f));
  fs.cpSync(path.join(REPO, "scripts"), path.join(dir, "scripts"), { recursive: true });
  fs.cpSync(path.join(REPO, "modules"), path.join(dir, "modules"), { recursive: true });
  fs.cpSync(path.join(REPO, "public"), path.join(dir, "public"), { recursive: true });
  // Dependencies are copied INTO the staged dir rather than reached via
  // NODE_PATH — module resolution across a network-mapped repo drive (SMB)
  // hangs in spawned children on Windows (hardware-verified 2026-08-16:
  // require("express") over \\server\share freezes indefinitely in a child
  // process while working fine interactively). The Docker image gets
  // node_modules from `npm install` anyway, so the Issue #1
  // app-file-completeness check is unchanged: the DOCKER_SET list above is
  // still the thing under test.
  fs.cpSync(path.join(REPO, "node_modules"), path.join(dir, "node_modules"), { recursive: true });
}

let CHILD = null;
async function startHub(dir, envExtra) {
  CHILD = spawn(process.execPath, ["server.js"], {
    cwd: dir, stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, ...(envExtra || {}) }
  });
  let log = "";
  CHILD.stdout.on("data", d => log += d);
  CHILD.stderr.on("data", d => log += d);
  for (let i = 0; i < 60; i++) {
    await sleep(250);
    try { const r = await fetch(HUB + "/api/version"); if (r.ok) return log; } catch {}
    if (CHILD.exitCode !== null) throw new Error("hub exited early:\n" + log);
  }
  throw new Error("hub never came up:\n" + log);
}
async function stopHub() {
  if (!CHILD) return;
  CHILD.kill("SIGTERM");
  await new Promise(r => { CHILD.on("exit", r); setTimeout(r, 2000); });
  CHILD = null;
}

