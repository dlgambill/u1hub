    ok(rp.status === 200 && JSON.stringify(rp.body.existingMixes) === JSON.stringify(jb.existingMixes) && rp.body.maxUid === 9,
      "analyze-parts (client-extracted configs) matches the whole-file path", rp.body.existingMixes);
    ok(rp.body.hasUsage === true && rp.body.colors[0].hex === "#FF0000" && rp.body.colors[0].parts === 2,
      "analyze-parts ranks usage from model_settings text", rp.body.colors);
