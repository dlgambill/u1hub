    let d = decodeMixedDefEntry("2,4,1,1,40,0,g,w,m2,z0,xa0,xb0,d0,o0,u7,cm0");
    ok(d && d.filaments.join(",") === "2,4" && d.weights.join(",") === "60,40",
      "m2 pair decodes as F2 60% + F4 40% (the previously-DROPPED format)", d);
    d = decodeMixedDefEntry("1,2,1,1,50,0,g123,w20/30/50,m0,z0,xa0,xb0,d0,o0,u3,cm0");
    ok(d && d.filaments.join(",") === "1,2,3" && d.weights.join(",") === "20,30,50", "m0 list decodes 20/30/50", d);
    // Round trip: everything we emit parses back to the identical recipe.
    const cases = [
      [{ slot: 1, pct: 55 }, { slot: 3, pct: 45 }],
      [{ slot: 2, pct: 5 }, { slot: 3, pct: 90 }, { slot: 4, pct: 5 }],
      [{ slot: 1, pct: 33 }, { slot: 2, pct: 33 }, { slot: 4, pct: 34 }]
    ];
    ok(cases.every(c => {
      const dd = decodeMixedDefEntry(defString(c, 9));
      const sorted = [...c].sort((a, b) => a.slot - b.slot);
      return dd && dd.filaments.join() === sorted.map(x => x.slot).join() && dd.weights.join() === sorted.map(x => x.pct).join();
    }), "emit → decode round trip is exact for pairs and triples");
    let threw = false;
    try { defString([{ slot: 1, pct: 60 }, { slot: 2, pct: 50 }], 1); } catch { threw = true; }
