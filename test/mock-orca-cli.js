// test/mock-orca-cli.js — stand-in for orca-slicer.exe in the harness.
// Invoked as: node mock-orca-cli.js [MODE] --slice N --debug 2 --outputdir DIR SRC.3MF
// (the slicing module's cfg.slicer.prefixArgs hook injects [script, MODE]).
//
// Modes:
//   ok       — writes plate_1.gcode (Orca-style config tail), exit 0
//   silent   — exit 5, NO output, NO gcode  (Snapmaker-CLI 0xC0000005 shape)
//   honest   — stderr error, exit 1 (pure-Bambu placeholder error)
//   eaten    — exit 0 but NO gcode  (GUI single-instance forwarding)
//   deaf     — exit 0, gcode ignores settings (applied-echo mismatch fixture)
//   twoplate — exit 0, writes plate_1 + plate_2 (arrange-spill fixture)
"use strict";
const fs = require("fs");
const path = require("path");
const argv = process.argv.slice(2);
let mode = ["ok", "silent", "honest", "eaten", "deaf", "twoplate"].includes(argv[0]) ? argv.shift() : "ok";
// Harness hook: mode FILE outranks positional mode — run-tests.js can flip
// failure shapes between enqueues without restarting the Hub.
if (process.env.U1SLICE_MOCK_MODE_FILE) {
  try { const m = fs.readFileSync(process.env.U1SLICE_MOCK_MODE_FILE, "utf8").trim(); if (m) mode = m; } catch {}
}
const oi = argv.indexOf("--outputdir");
const outDir = oi >= 0 ? argv[oi + 1] : null;
const src = argv[argv.length - 1];

if (mode === "silent") process.exit(5);
if (mode === "honest") { process.stderr.write("Unknown placeholder filament_is_high_temperature in machine start gcode\n"); process.exit(1); }
if (mode === "eaten") { process.stdout.write("[info] forwarding to running instance\n"); process.exit(0); }

const head = Buffer.alloc(4);
const fd = fs.openSync(src, "r"); fs.readSync(fd, head, 0, 4, 0); fs.closeSync(fd);
if (head.readUInt32LE(0) !== 0x04034b50) { process.stderr.write("input is not a zip/3mf\n"); process.exit(2); }
process.stdout.write("[info] slicing " + path.basename(src) + "\n");
const flagVal = f => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : null; };
const tailDefaults = { layer_height: "0.2", sparse_infill_density: "15%", enable_support: "0", wall_loops: "2",
  sparse_infill_pattern: "grid", brim_type: "auto_brim", top_shell_layers: "4", bottom_shell_layers: "3" };
const tail = { ...tailDefaults };
if (mode !== "deaf")
  for (const k of Object.keys(tailDefaults)) {
    const v = flagVal("--" + k.replace(/_/g, "-"));
    if (v !== null) tail[k] = v;
  }
fs.writeFileSync(path.join(outDir, "plate_1.gcode"), [
  "; generated by OrcaSlicer 2.4.2 (mock)",
  "; args = " + argv.join(" "),
  "G28", "G1 X10 Y10", "G1 E5",
  "; filament_colour = #FF0000",
  "; filament_type = PLA",
  ...Object.entries(tail).map(([k, v]) => "; " + k + " = " + v),
  "; filament used [g] = 12.0",
  "; estimated printing time (normal mode) = 1h 30m",
  ""
].join("\n"));
if (mode === "twoplate")
  fs.writeFileSync(path.join(outDir, "plate_2.gcode"),
    "; generated by OrcaSlicer 2.4.2 (mock)\nG28\nG1 X5\n; estimated printing time (normal mode) = 1h 20m\n");
process.stdout.write("[info] result exported\n");
process.exit(0);
